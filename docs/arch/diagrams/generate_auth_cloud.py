def auth():
    d=Diagram(2400,1770,'BUNZINA / SEQUÊNCIA DE AUTENTICAÇÃO','POST /auth/login · fluxo definido no RFC 001')
    xs=[210,700,1190,1680,2170]
    titles=['Cliente','API Gateway','Lambda Auth','API no EKS','PostgreSQL']
    descriptions=[['Login por CPF'],['HTTP API'],['Validação de entrada'],['Autenticação + JWT'],['Usuários / clientes']]
    for x,title,lines in zip(xs,titles,descriptions):
        d.box(x-185,175,370,115,title,lines,color='#6d28d9' if x==1680 else '#2563eb')
        d.line([(x,290),(x,1690)],dash=True,arrow=False,color='#a5b2c5')
    c,g,l,a,b=xs
    d.message(c,g,360,'1. POST /auth/login')
    d.text((c+g)/2,391,'{ document, password }',20,anchor='middle')
    d.message(g,l,450,'2. Encaminha a requisição')
    d.rect(l-200,485,400,88,'#eaf1ff')
    d.text(l,520,'3. Valida payload e CPF',22,bold=True,anchor='middle')
    d.text(l,552,'Dígitos verificadores',20,anchor='middle')
    d.message(l,a,635,'4. POST /auth/login via Axios')
    d.text((l+a)/2,666,'{ document, password }',20,anchor='middle')
    d.message(a,b,735,'5. Consulta de autenticação')
    d.message(b,a,815,'6. Dados de usuário / cliente',reply=True)
    d.rect(a-200,855,400,135,'#f0eafb')
    d.text(a,892,'7. Valida credenciais',22,bold=True,anchor='middle')
    d.text(a,926,'Verifica senha e status',20,anchor='middle')
    d.text(a,960,'Gera JWT',23,bold=True,anchor='middle')
    d.message(a,l,1050,'8. HTTP 200 + { token }',reply=True)
    d.message(l,g,1130,'9. Repassa status e body',reply=True)
    d.message(g,c,1210,'10. Resposta de login',reply=True)
